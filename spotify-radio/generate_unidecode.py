"""Generate features/unidecode_table.c from the Unidecode wheel (GPL-2.0-or-later, Sean M. Burke /
Tomaz Solc). The x???.py tables are read with ast as data; nothing from the wheel is executed.
Usage: python generate_unidecode.py /path/to/Unidecode-1.3.8-py3-none-any.whl
Covers the Basic Multilingual Plane except CJK ideographs (pinyin_table.c), Hangul syllables
(romanized in code), surrogates and private use.
"""

import ast
from pathlib import Path
import sys
import zipfile

OUTPUT = Path(__file__).resolve().parent / "unidecode_table.c"
SKIP_PAGES = set(range(0x4E, 0xA0)) | set(range(0xAC, 0xD8)) | set(range(0xD8, 0xF9))
NONE = 0xFFFF


def read_page(archive, page):
    name = f"unidecode/x{page:03x}.py"
    if name not in archive.namelist():
        return None
    tree = ast.parse(archive.read(name).decode("utf-8"))
    node = next(n for n in tree.body if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "data")
    return ast.literal_eval(node.value)


def clean(text):
    if text is None:
        return None
    # "`" marks ayin and similar; on a HUD banner it only reads as a stray symbol
    text = "".join(c for c in text if 0x20 <= ord(c) <= 0x7E and c != "`")
    return None if text in ("", "[?]") else text


def main():
    archive = zipfile.ZipFile(sys.argv[1])
    pool = bytearray()
    offsets = {}
    pages = []  # (page, [offset or NONE] * 256)
    for page in range(0x00, 0x100):
        if page in SKIP_PAGES:
            continue
        data = read_page(archive, page)
        if data is None:
            continue
        row = []
        for i in range(256):
            text = clean(data[i]) if i < len(data) else None
            if page == 0 and i < 0x80:
                text = None  # ASCII is passed through by the caller
            if text is None:
                row.append(NONE)
                continue
            if text not in offsets:
                offsets[text] = len(pool)
                pool += text.encode("ascii") + b"\0"
            row.append(offsets[text])
        if any(v != NONE for v in row):
            pages.append((page, row))
    assert len(pool) < NONE

    page_index = [0] * 256
    for slot, (page, _) in enumerate(pages, start=1):
        page_index[page] = slot

    lines = [
        "/* Generated by generate_unidecode.py from Unidecode 1.3.8 (GPL-2.0-or-later; Copyright 2001",
        " * Sean M. Burke, 2009-2024 Tomaz Solc). Do not edit. ASCII approximations for the BMP. */",
        '#include "unidecode_table.h"',
        "",
        f"static const unsigned char page_index[256] = {{",
    ]
    for i in range(0, 256, 32):
        lines.append("    " + " ".join(f"{v}," for v in page_index[i:i + 32]))
    lines += ["};", "", f"static const unsigned short entries[{len(pages)}][256] = {{"]
    for page, row in pages:
        lines.append(f"    {{ /* U+{page:02X}xx */")
        for i in range(0, 256, 16):
            lines.append("        " + " ".join(f"{v}," for v in row[i:i + 16]))
        lines.append("    },")
    lines += ["};", "", f"static const char pool[{len(pool)}] ="]
    chunk = 96
    for i in range(0, len(pool), chunk):
        part = pool[i:i + chunk]
        escaped = "".join("\\0" if b == 0 else ("\\" + chr(b) if chr(b) in '"\\' else chr(b)) for b in part)
        # "\0" followed by a digit would read as an octal escape; break the literal there
        escaped = escaped.replace("\\0", '\\0""')
        lines.append(f'    "{escaped}"')
    lines[-1] += ";"
    lines += [
        "",
        "const char *unidecode_lookup(unsigned int codepoint) {",
        "    if (codepoint > 0xFFFF) {",
        "        return NULL;",
        "    }",
        "    unsigned int slot = page_index[codepoint >> 8];",
        "    if (!slot) {",
        "        return NULL;",
        "    }",
        "    unsigned short offset = entries[slot - 1][codepoint & 0xFF];",
        f"    return offset == 0x{NONE:X} ? NULL : pool + offset;",
        "}",
        "",
    ]
    OUTPUT.write_text("\r\n".join(lines), encoding="ascii", newline="")
    covered = sum(1 for _, row in pages for v in row if v != NONE)
    print(f"{OUTPUT}: {covered} characters in {len(pages)} pages, pool {len(pool)} bytes")


if __name__ == "__main__":
    main()
